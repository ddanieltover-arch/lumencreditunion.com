/** Primary markets with full product defaults (loans + cards). */
const PRIMARY_MARKET_CODES = new Set(['US', 'CA', 'GB', 'DE', 'FR', 'NL', 'ES', 'IT', 'IE']);

const PRIMARY_ACCEPTED_IDS: Record<string, string[]> = {
  US: ['PASSPORT', 'DRIVERS_LICENSE', 'ID_CARD'],
  CA: ['PASSPORT', 'DRIVERS_LICENSE', 'ID_CARD'],
  GB: ['PASSPORT', 'DRIVERS_LICENSE', 'RESIDENCE_PERMIT', 'BRP'],
  DE: ['PASSPORT', 'ID_CARD', 'DRIVERS_LICENSE'],
  FR: ['PASSPORT', 'ID_CARD', 'RESIDENCE_PERMIT', 'DRIVERS_LICENSE'],
  NL: ['PASSPORT', 'ID_CARD', 'RESIDENCE_PERMIT', 'DRIVERS_LICENSE'],
  ES: ['PASSPORT', 'ID_CARD', 'RESIDENCE_PERMIT', 'DRIVERS_LICENSE'],
  IT: ['PASSPORT', 'ID_CARD', 'DRIVERS_LICENSE'],
  IE: ['PASSPORT', 'DRIVERS_LICENSE', 'RESIDENCE_PERMIT'],
};

function toSeedCountry(
  code: string,
  name: string,
  currency: string,
  currencySymbol: string,
): SeedCountry {
  const isPrimary = PRIMARY_MARKET_CODES.has(code);
  return {
    code,
    name,
    currency,
    currencySymbol,
    enabled: true,
    acceptedIdTypes: PRIMARY_ACCEPTED_IDS[code] ?? ['PASSPORT', 'DRIVERS_LICENSE', 'ID_CARD'],
    autoLoansEnabled: isPrimary && code !== 'NL' && code !== 'IT',
    mortgageEnabled: isPrimary && (code === 'US' || code === 'CA'),
    cardsEnabled: true,
    isSanctioned: false,
    sanctionReason: null,
  };
}

export const SEEDED_COUNTRIES: SeedCountry[] = WORLD_COUNTRY_ROWS.map(([code, name, currency, symbol]) =>
  toSeedCountry(code, name, currency, symbol),
).sort((a, b) => a.name.localeCompare(b.name));

